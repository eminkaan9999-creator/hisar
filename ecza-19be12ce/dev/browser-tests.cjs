'use strict';
const { chromium } = require('playwright');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const appRoot = path.join(root, 'ecza-19be12ce');
const output = path.join(appRoot, 'test-results');
fs.mkdirSync(output, { recursive: true });
const html = fs.readFileSync(path.join(appRoot, 'index.html'), 'utf8');
const V = JSON.parse(/<script\b[^>]*id="veri"[^>]*>([\s\S]*?)<\/script>/.exec(html)[1]);
const normalize = s => s.toLocaleLowerCase('tr').replace(/ı/g, 'i').normalize('NFD').replace(/[\u0300-\u036f]/g, '');
const counts = {};
for (const u of V.urun) { const c = normalize(u.ad)[0]; if (/[a-z]/.test(c)) counts[c] = (counts[c] || 0) + 1; }
const query = Object.keys(counts).sort((a, b) => counts[b] - counts[a])[0];
const product = V.urun.find(u => normalize(u.ad).startsWith(query) && u.form && u.mol);
assert(product, 'Need a real product for UI tests');
const other = V.urun.find(u => u.id !== product.id);
const group = u => u.mol && V.mol[u.mol] ? V.mol[u.mol].grup : u.grup || 'diger';
const server = http.createServer((req, res) => {
  const url = new URL(req.url, 'http://localhost');
  let target = path.resolve(root, '.' + decodeURIComponent(url.pathname));
  if (!target.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
  if (fs.existsSync(target) && fs.statSync(target).isDirectory()) target = path.join(target, 'index.html');
  if (!fs.existsSync(target)) { res.writeHead(404).end('Not found'); return; }
  const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.jpg': 'image/jpeg', '.png': 'image/png' };
  res.writeHead(200, { 'Content-Type': types[path.extname(target)] || 'application/octet-stream', 'Cache-Control': 'no-cache' });
  fs.createReadStream(target).pipe(res);
});
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}/ecza-19be12ce/`;
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
  await context.addInitScript(({ id }) => {
    if (!localStorage.getItem('ilacdefteri.v2')) localStorage.setItem('ilacdefteri.v2', JSON.stringify({ puan: 123, seri: 2, enIyi: 5, tur: 3, fav: { [id]: 1 }, kutu: { [id]: 3 }, son: [id] }));
  }, { id: product.id });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  const pass = name => { checks.push({ name, passed: true }); console.log('PASS ' + name); };
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('ilacdefteri.v2')));
  const search = async value => { await page.locator('#q').fill(value); await page.waitForTimeout(220); await page.locator('#ux-search-status').waitFor(); };
  const nav = async tab => {
    const dock = page.locator(`.ux-dock [data-id="${tab}"]`);
    if (await dock.isVisible()) await dock.click();
    else {
      const menu = page.locator(`#menunav [data-id="${tab}"]`);
      if (!(await menu.isVisible())) await page.locator('#navbtn').click();
      await menu.click();
    }
    await page.waitForTimeout(120);
  };
  try {
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await page.locator('.ux-overview').waitFor();
    assert.equal(await page.evaluate(() => window.ECZ.surum), 7);
    assert.equal((await state()).puan, 123);
    pass('Version 7 boots and preserves existing progress');
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: width > 900 ? 1000 : 844 });
      await page.waitForTimeout(100);
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
      assert(await page.evaluate(() => { const v = document.querySelector('#view'); return v.scrollWidth <= v.clientWidth + 1; }));
      await page.screenshot({ path: path.join(output, `home-${width}.png`) });
      pass('Home layout fits ' + width + 'px');
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await search(query);
    const before = await page.locator('#ux-results .row').count();
    assert.equal(before, 40);
    await page.locator('[data-ux="more"]').click();
    assert((await page.locator('#ux-results .row').count()) > before);
    pass('Pagination exposes results beyond the first 40');
    await page.locator('#ux-group').selectOption(group(product));
    let ids = await page.locator('#ux-results .row').evaluateAll(nodes => nodes.map(n => n.dataset.id));
    assert(ids.every(id => group(V.urun.find(u => u.id === id)) === group(product)));
    await page.locator('#ux-form').selectOption(product.form);
    ids = await page.locator('#ux-results .row').evaluateAll(nodes => nodes.map(n => n.dataset.id));
    assert(ids.length > 0 && ids.every(id => V.urun.find(u => u.id === id).form === product.form));
    await page.locator('#ux-order').selectOption('az');
    assert(await page.evaluate(() => { const names = [...document.querySelectorAll('#ux-results .row .nm')].map(e => e.textContent); return names.every((n, i) => !i || names[i - 1].localeCompare(n, 'tr') <= 0); }));
    pass('Group, form and alphabetical filters work');
    await page.locator('[data-ux="clear-filters"]').click();
    await search(product.ad);
    await page.locator('[data-ux="fav-filter"]').click();
    assert.equal(await page.locator('#ux-results .row').count(), 1);
    pass('Favorites filter uses the saved notebook');
    await page.locator(`#ux-results [data-id="${product.id}"]`).click();
    const note = '<img src=x onerror=alert(1)> Öğrenme notu';
    await page.locator('#ux-note').fill(note);
    assert.equal((await state()).notes[product.id], note);
    await page.locator('#kart [data-a="kapat"]').click();
    await page.waitForTimeout(200);
    await page.locator(`#ux-results [data-id="${product.id}"]`).click();
    assert.equal(await page.locator('#ux-note').inputValue(), note);
    assert.equal(await page.locator('.ux-note img').count(), 0);
    pass('Notes persist and are escaped instead of interpreted as HTML');
    await page.locator('#kart [data-a="kapat"]').click();
    await page.waitForTimeout(200);
    await nav('defterim');
    await page.locator('#ux-theme').selectOption('dark');
    await page.locator('#ux-large').check();
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.locator('#ux-theme').waitFor();
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    assert(await page.locator('#ux-large').isChecked());
    assert(await page.evaluate(() => parseFloat(getComputedStyle(document.querySelector('.hint')).fontSize) >= 17));
    pass('Dark theme and larger text survive reload');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('[data-ux="export"]').click();
    const download = await downloadPromise;
    const exportPath = path.join(output, 'test-backup.json');
    await download.saveAs(exportPath);
    const backup = JSON.parse(fs.readFileSync(exportPath, 'utf8'));
    assert.equal(backup.app, 'kardelen-ilac-defteri');
    assert.equal(backup.data.notes[product.id], note);
    pass('Backup export contains local notes and progress');
    const baseline = JSON.stringify(await state());
    await page.locator('#ux-import').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"bad":true}') });
    await page.waitForTimeout(150);
    assert((await page.locator('#ux-import-preview').innerText()).includes('Dosya okunamadı'));
    assert.equal(JSON.stringify(await state()), baseline);
    pass('Invalid backup is rejected without changing saved data');
    const incoming = { app: 'kardelen-ilac-defteri', schema: 1, data: { fav: { [other.id]: 1, unknown_id: 1 }, notes: { [product.id]: 'Must not overwrite', [other.id]: 'Imported note' }, kutu: { [product.id]: 0 }, puan: -1 } };
    const upload = { name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(incoming)) };
    await page.locator('#ux-import').setInputFiles(upload);
    await page.locator('[data-ux="import-cancel"]').click();
    assert.equal(JSON.stringify(await state()), baseline);
    pass('Import preview can be cancelled without changes');
    await page.locator('#ux-import').setInputFiles(upload);
    await page.locator('[data-ux="import-confirm"]').click();
    const merged = await state();
    assert.equal(merged.notes[product.id], note);
    assert.equal(merged.notes[other.id], 'Imported note');
    assert.equal(merged.fav[other.id], 1);
    assert(!merged.fav.unknown_id);
    assert.equal(merged.puan, 123);
    assert.equal(merged.kutu[product.id], 3);
    pass('Backup merge preserves existing notes, score and progress');
    await page.screenshot({ path: path.join(output, 'notebook-dark.png') });
    await nav('raflar');
    await page.locator('.shot').first().click();
    await page.locator('#ux-zoom').waitFor();
    await page.locator('[data-ux="zoom-in"]').click();
    assert.equal(await page.locator('#ux-zoom-value').innerText(), '150%');
    await page.locator('[data-ux="zoom-reset"]').click();
    assert.equal(await page.locator('#ux-zoom-value').innerText(), '100%');
    assert(await page.locator('[data-ux="zoom-out"]').isDisabled());
    await page.screenshot({ path: path.join(output, 'shelf-controls.png') });
    pass('Shelf zoom, fit and zoom boundaries work');
    await page.locator('[data-a="fkapat"]').click();
    await page.waitForTimeout(150);
    await nav('ara');
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.waitForFunction(() => !!navigator.serviceWorker.controller);
    await context.setOffline(true);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.locator('.ux-overview').waitFor();
    assert((await page.locator('.ux-network').innerText()).includes('Çevrimdışı'));
    await search(product.ad);
    assert((await page.locator('#ux-results .row').count()) > 0);
    assert.equal((await state()).notes[product.id], note);
    pass('Offline reload, search and local notes work');
    assert.deepEqual(errors, []);
    pass('No uncaught browser errors');
  } catch (error) {
    checks.push({ name: 'Failure', passed: false, message: error.stack });
    await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
    process.exitCode = 1;
    console.error(error);
  } finally {
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ checks, browserErrors: errors, productCount: V.urun.length, timestamp: new Date().toISOString() }, null, 2));
    await browser.close(); server.close();
  }
})();
