'use strict';
const assert=require('node:assert/strict');
exports.menu=async function(page,{label,ok}){
  const pick=k=>page.locator('#mp .tabs [data-t="'+k+'"]').click();
  const stops=page.locator('#operation-plan .journey-stop');
  assert.equal(await stops.count(),6);
  const scene=()=>page.locator('#journey-postcard canvas').evaluate(c=>c.toDataURL());
  const first=await scene();
  await stops.nth(4).click();
  assert.equal(await page.locator('#journey-postcard strong').innerText(),'Dönüş yolu');
  assert.notEqual(await scene(),first);
  assert.equal(await page.evaluate(()=>HisarHarekat.diagnostics().active),false);
  await stops.first().click();
  await page.locator('#sf-archive').click();
  const archive=page.locator('#journey-archive');
  await archive.locator('input').fill('kirik');
  assert.equal(await page.locator('#hkCard [data-op]:visible').count(),1);
  await archive.locator('input').fill('');
  await archive.locator('select').selectOption('done');
  assert.equal(await archive.locator('small').innerText(),'Eşleşen görev yok');
  await page.locator('#sf-archive').click();
  assert.equal(await archive.count(),0);
  ok(label+': illustrated stage previews, Turkish archive search and completion filter keep the actual mission intact');
  await pick('b');
  const values=()=>page.evaluate(()=>SV.load.slice());
  const initial=await values();
  await page.locator('#ld [data-ld="0:-2"]').click();
  assert.notDeepEqual(await values(),initial);
  await page.locator('#journey-undo').click();assert.deepEqual(await values(),initial);
  await pick('u');
  await page.locator('#journey-garage input').check();
  assert.equal(await page.locator('#upl .uc:visible button:disabled').count(),0);
  await page.locator('#journey-garage input').uncheck();
  await pick('k');
  await page.locator('#tk .kseg [data-k="k"]').click();
  await page.locator('#journey-controls input').fill('harita');
  assert.equal(await page.locator('#tk .klist[data-k="k"] .kk:visible').count(),1);
  await page.locator('#journey-controls input').fill('');
  ok(label+': loadout undo, affordable upgrades and command lookup operate on real menu data');
  await pick('g');
  await page.locator('#hisar-experience-entry').click();
  await page.locator('#journey-access summary').click();
  for(const key of ['read','still']){
    await page.locator('#journey-'+key).check();
    assert.equal(await page.locator('body').evaluate((e,k)=>e.classList.contains('journey-'+k),key),true);
    await page.locator('#journey-'+key).uncheck();
  }
  await page.locator('#journey-access summary').click();await page.locator('#hx-close').click();
  ok(label+': reading size and motion toggles are usable through native settings');
};
